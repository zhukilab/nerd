// Every NERD_* setting of the project in one list (process ticket 097): what it does, what reads it, its
// type and default, and what a change needs before it acts. /nerd in Pi and ./SETTINGS on the host
// are built on it, and so are the settings part of the docs and env.example; a test keeps the code and
// this list in step (no NERD_* read anywhere that is not here).

import { RING_DEFAULT, RING_SETTING, RINGS, TURN_KINDS_DEFAULT, WAYS } from "./letter-delivery.ts";

/** Who reads it: ./UP and the tools on the host (.env), the model server's container, or the agent (Pi). */
export type Owner = "host" | "server" | "agent";

/**
 * What a change needs before it acts:
 * - turn: read again for every request or tool call, so it acts from the next one;
 * - reload: read when Pi loads the extensions, so /reload (or /nerd, which reloads) applies it;
 * - restart: read when the Pi process starts (tui.ts, run.ts): Pi has to be restarted;
 * - up: read by ./UP or a container's entrypoint: ./UP recreates what it concerns.
 */
export type Apply = "turn" | "reload" | "restart" | "up";

export type Kind =
	| { type: "bool" } // "1" / "0"
	| { type: "choice"; choices: string[] }
	| { type: "int"; min?: number; max?: number }
	| { type: "text" };

/**
 * user: shown by default; advanced: shown on request; internal: set by ./UP or an entrypoint for the
 * process it starts (an address, a path), never by hand -- listed so that the check knows it.
 */
export type Level = "user" | "advanced" | "internal";

export interface Setting {
	name: string;
	owner: Owner;
	/** A heading the settings are shown under. */
	group: string;
	kind: Kind;
	/** The value used when it is unset, as text; "" when it is worked out (the summary says how). */
	default: string;
	/** One or two sentences: what it does and, for a choice, what each value means. */
	summary: string;
	apply: Apply;
	level: Level;
	/** Another name that is still read for it. */
	alias?: string;
}

